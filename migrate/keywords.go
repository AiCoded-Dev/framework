package migrate

import "strings"

// keywords are the words, in upper case, that Normalize upper-cases: the keywords, types and
// functions of the statements the checks read, and of plain INSERT, UPDATE, DELETE and SELECT.
// Every other word is a name and keeps its case.
var keywords = func() map[string]bool {
	m := map[string]bool{}
	for _, w := range strings.Fields(`
		ACTION ADD AFTER ALGORITHM ALL ALTER ALWAYS AND AS ASC AUTO_INCREMENT
		BETWEEN BTREE BY CASCADE CASE CHANGE CHARACTER CHARSET CHECK COLLATE COLUMN COMMENT
		CONSTRAINT CREATE CROSS DEFAULT DELETE DESC DISTINCT DROP DUPLICATE ELSE END ENFORCED
		ENGINE EXISTS FIRST FOREIGN FROM FULL FULLTEXT GENERATED GROUP HASH HAVING IF IGNORE IN
		INDEX INNER INSERT INTO INVISIBLE IS JOIN KEY LEFT LIKE LIMIT MATCH MODIFY NO NOT NULL
		OFFSET ON OR ORDER OUTER PARTIAL PRIMARY REFERENCES RENAME REPLACE RESTRICT RIGHT
		ROW_FORMAT SELECT SET SIMPLE SPATIAL STORED TABLE TEMPORARY THEN TO TRUNCATE UNION UNIQUE
		UNSIGNED UPDATE USING VALUE VALUES VIRTUAL VISIBLE WHEN WHERE ZEROFILL

		BIGINT BINARY BIT BLOB BOOL BOOLEAN CHAR DATE DATETIME DEC DECIMAL DOUBLE ENUM FIXED
		FLOAT GEOMETRY INT INTEGER JSON LINESTRING LONGBLOB LONGTEXT MEDIUMBLOB MEDIUMINT
		MEDIUMTEXT NATIONAL NCHAR NUMERIC NVARCHAR POINT POLYGON PRECISION REAL SERIAL SMALLINT
		TEXT TIME TIMESTAMP TINYBLOB TINYINT TINYTEXT VARBINARY VARCHAR VARYING YEAR

		COMPACT COMPRESSED DYNAMIC INNODB REDUNDANT
		CURRENT_DATE CURRENT_TIME CURRENT_TIMESTAMP FALSE LOCALTIME LOCALTIMESTAMP NOW TRUE
		UTC_DATE UTC_TIME UTC_TIMESTAMP UUID
	`) {
		m[w] = true
	}
	return m
}()
